import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { createBrowserSession } from './browser-session.mjs'
const browser = await createBrowserSession()
const { evaluate,waitFor } = browser
async function navigate(route,title) {
  await browser.send('Page.navigate',{ url: 'http://localhost:5173' + route })
  for (let attempt=0;attempt<200;attempt++) { if (await evaluate(`document.querySelector('h1')?.textContent === ${JSON.stringify(title)}`)) break; await new Promise(resolve=>setTimeout(resolve,100)) }
  await waitFor(`document.querySelector('h1')?.textContent === ${JSON.stringify(title)}`)
  await evaluate(`document.fonts.ready.then(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))))`)
}
async function link(text) { await evaluate(`Array.from(document.querySelectorAll('main a')).find(link=>link.textContent.trim() === ${JSON.stringify(text)}).click()`); await evaluate(`new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))`) }
const button = text => evaluate(`Array.from(document.querySelectorAll('main button')).find(button=>button.textContent.trim() === ${JSON.stringify(text)}).click()`)
const click = label => evaluate(`document.querySelector('[aria-label=${JSON.stringify(label)}]').click()`)
const menu = async text => { await click('Integration actions'); await button(text) }
try {
  await browser.viewport(1588,991)
  await navigate('/integrations?source=github','Integrations')
  await evaluate(`sessionStorage.removeItem('menaiq-source-prototype-v1')`)
  await navigate('/integrations?source=github','Integrations')
  assert.equal(await evaluate(`document.querySelector('#integration-details').textContent.includes('Connected (demo)')`),true)
  assert.equal(await evaluate(`document.querySelector('#integration-details').textContent.includes('Delayed')`),false)
  assert.equal(await evaluate(`document.querySelector('#integration-details').textContent.includes('Last Successful Sync')`),false)
  await browser.capture('integrations-separated-desktop')
  await link('View Reporting Health')
  await waitFor(`document.querySelector('h1')?.textContent === 'Coverage & Health'`)
  assert.equal(await evaluate(`location.pathname + location.search`),'/coverage-health?source=github')
  assert.equal(await evaluate(`document.querySelector('#source-detail h2').textContent`),'GitHub Integration')
  assert.equal(await evaluate(`document.querySelector('#source-detail').textContent.includes('Connected (demo)')`),true)
  assert.equal(await evaluate(`document.querySelector('#source-detail').textContent.includes('Delayed')`),true)
  await browser.capture('coverage-separated-desktop')
  await link('View Integration Settings')
  await waitFor(`document.querySelector('h1')?.textContent === 'Integrations'`)
  assert.equal(await evaluate(`document.querySelector('#integration-details h2').textContent`),'GitHub App')
  await evaluate(`history.back()`)
  await waitFor(`location.pathname === '/coverage-health' && document.querySelector('#source-detail h2')?.textContent === 'GitHub Integration'`)
  await evaluate(`history.forward()`)
  await waitFor(`location.pathname === '/integrations' && document.querySelector('#integration-details h2')?.textContent === 'GitHub App'`)
  for (const [scenario,id,health] of [['github-healthy','github','Healthy'],['github-delayed','github','Delayed'],['litellm-degraded','litellm','Degraded']]) {
    await navigate(`/integrations?source=${id}&scenario=${scenario}`,'Integrations')
    assert.equal(await evaluate(`document.querySelector('#integration-details').textContent.includes('Connected (demo)')`),true)
    await link('View Reporting Health')
    await waitFor(`document.querySelector('h1')?.textContent === 'Coverage & Health'`)
    assert.equal(await evaluate(`document.querySelector('#source-detail').textContent.includes(${JSON.stringify(health)})`),true)
    assert.equal(await evaluate(`document.querySelector('[data-source-id=${id}]').getAttribute('aria-pressed')`),'true')
    await link('View Integration Settings')
    await waitFor(`document.querySelector('h1')?.textContent === 'Integrations'`)
    assert.equal(await evaluate(`new URLSearchParams(location.search).get('scenario')`),scenario)
  }
  await navigate('/integrations?source=github','Integrations')
  await menu('Disconnect demo')
  await waitFor(`!!document.querySelector('dialog[open]')`)
  await button('Confirm disconnect')
  await waitFor(`!document.querySelector('dialog[open]') && document.querySelector('#integration-details').textContent.includes('Disconnected (demo)')`)
  await link('View Reporting Health')
  await waitFor(`document.querySelector('#source-detail')?.textContent.includes('Disconnected (demo)')`)
  assert.equal(await evaluate(`document.querySelector('#source-detail').textContent.includes('Not Available observed')`),true)
  assert.equal(await evaluate(`document.querySelector('#source-detail').textContent.includes('0 observed')`),false)
  await navigate('/coverage-health?source=github','Coverage & Health')
  assert.equal(await evaluate(`document.querySelector('#source-detail').textContent.includes('Disconnected (demo)')`),true,'Direct URL retains shared tab-session config')
  await link('View Integration Settings')
  await waitFor(`document.querySelector('#integration-details')?.textContent.includes('Disconnected (demo)')`)
  await menu('Connect demo')
  await waitFor(`!!document.querySelector('dialog[open]')`)
  await evaluate(`(() => { const el=document.querySelector('[aria-label="Demo workspace"]'); el.value='prototype-workspace'; el.dispatchEvent(new Event('change',{bubbles:true})); })()`)
  await button('Apply demo setup')
  await waitFor(`!document.querySelector('dialog[open]') && document.querySelector('#integration-details').textContent.includes('Connected (demo)')`)
  await link('View Reporting Health')
  await waitFor(`document.querySelector('#source-detail')?.textContent.includes('Connected (demo)')`)
  assert.equal(await evaluate(`document.querySelector('#source-detail').textContent.includes('Delayed')`),true,'Connect does not claim healthy telemetry')
  await navigate('/coverage-health?source=github&scenario=github-not-configured','Coverage & Health')
  assert.equal(await evaluate(`document.querySelector('#source-detail').textContent.includes('Not Configured')`),true)
  assert.equal(await evaluate(`document.querySelector('#source-detail').textContent.includes('Not Available observed')`),true)
  await link('View Integration Settings')
  await waitFor(`document.querySelector('#integration-details')?.textContent.includes('Not Configured (demo)')`)
  for (const role of ['viewer','manager']) {
    await navigate(`/integrations?source=litellm&role=${role}&scope=data&period=7`,'Integrations')
    await click('Integration actions')
    assert.equal(await evaluate(`Array.from(document.querySelectorAll('#integration-details details button')).every(button=>button.disabled)`),true)
    await link('View Reporting Health')
    await waitFor(`document.querySelector('h1')?.textContent === 'Coverage & Health'`)
    assert.equal(await evaluate(`new URLSearchParams(location.search).get('role')`),role)
    assert.equal(await evaluate(`new URLSearchParams(location.search).get('scope')`),'data')
    await link('View Integration Settings')
    await waitFor(`document.querySelector('h1')?.textContent === 'Integrations'`)
    await click('Integration actions')
    assert.equal(await evaluate(`Array.from(document.querySelectorAll('#integration-details details button')).every(button=>button.disabled)`),true)
  }
  for (const [route,title,selector] of [['/integrations?source=unknown','Integrations','#integration-details'],['/coverage-health?source=unknown','Coverage & Health','#source-detail']]) {
    await navigate(route,title)
    assert.equal(await evaluate(`document.querySelector(${JSON.stringify(selector)}).textContent.toLowerCase().includes('not found')`),true)
  }
  await browser.viewport(390,844)
  await navigate('/integrations?source=github','Integrations')
  assert.equal(await evaluate(`document.documentElement.scrollWidth <= innerWidth`),true)
  await browser.capture('integrations-separated-mobile')
  await link('View Reporting Health')
  await waitFor(`document.querySelector('h1')?.textContent === 'Coverage & Health'`)
  assert.equal(await evaluate(`document.documentElement.scrollWidth <= innerWidth`),true)
  await browser.capture('coverage-separated-mobile')
  await browser.viewport(1588,991)
  for (const [route,title,name] of [['/company-overview','Company Overview','company'],['/entity-analytics','Entity Analytics','entity'],['/departments','Departments','departments'],['/sessions','Sessions','sessions'],['/code-traceability','Code Traceability','trace'],['/usage-cost','Usage & Cost','usage'],['/security-findings','Security Findings','security'],['/users-departments','Users & Departments','users']]) {
    await navigate(route,title)
    await waitFor(name === 'security' ? `document.querySelectorAll('[data-finding-id]').length === 5` : `!!document.querySelector('tbody')`)
    await browser.capture(name + '-after-source-separation')
    assert.equal((await readFile('.browser-qa/' + name + '-before-integrations.png')).equals(await readFile('.browser-qa/' + name + '-after-source-separation.png')),true,title + ' unchanged')
  }
  assert.deepEqual(browser.errors,[])
  console.log('Source separation browser checks passed: A–J scenarios, shared disconnect/reconnect across direct loads, role-preserving links, back/forward, invalid IDs, mobile, and all eight unrelated page screenshots unchanged.')
} catch(error) { console.error(await evaluate(`JSON.stringify({url:location.href,text:document.querySelector('main')?.textContent})`)); console.error(browser.errors); await browser.capture('source-navigation-failure'); throw error }
finally { await browser.close() }

import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { createBrowserSession } from './browser-session.mjs'
const browser = await createBrowserSession()
const { evaluate, waitFor } = browser
const previous = [['/company-overview','Company Overview','company'],['/entity-analytics','Entity Analytics','entity'],['/departments','Departments','departments'],['/sessions','Sessions','sessions'],['/code-traceability','Code Traceability','trace'],['/usage-cost','Usage & Cost','usage'],['/security-findings','Security Findings','security'],['/coverage-health','Coverage & Health','coverage']]
async function ready(name) { await waitFor(name === 'security' ? `document.querySelectorAll('[data-finding-id]').length === 5` : name === 'coverage' ? `document.querySelectorAll('[data-source-id]').length === 3` : `!!document.querySelector('tbody')`) }
try {
  await browser.viewport(1588, 991)
  if (process.argv.includes('--baseline')) {
    for (const [route,title,name] of previous) { await browser.navigate(route,title); await ready(name); await browser.capture(name + '-before-users') }
    console.log('Captured eight approved page baselines.')
  } else {
    const navigate = query => browser.navigate('/users-departments' + (query ?? ''), 'Users & Departments')
    const click = label => evaluate(`document.querySelector('[aria-label=${JSON.stringify(label)}]').click()`)
    const button = text => evaluate(`Array.from(document.querySelectorAll('main button')).find(button => button.textContent.trim() === ${JSON.stringify(text)}).click()`)
    async function input(label, value) {
      await evaluate(`(() => { const el = document.querySelector('input[aria-label=${JSON.stringify(label)}]'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(el, ${JSON.stringify(value)}); el.dispatchEvent(new Event('input', { bubbles: true })); })()`)
      await evaluate(`new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))`)
    }
    async function select(label,value) {
      await evaluate(`(() => { const el = document.querySelector('select[aria-label=${JSON.stringify(label)}]'); el.value = ${JSON.stringify(value)}; el.dispatchEvent(new Event('change', { bubbles: true })); })()`)
      await evaluate(`new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))`)
    }
    async function tab(index) { await evaluate(`document.getElementById('directory-tab-${index}').click()`); await waitFor(`document.getElementById('directory-tab-${index}').getAttribute('aria-selected') === 'true'`) }
    async function menu(text) { await click('User actions'); await button(text) }
    const openDialog = () => waitFor(`!!document.querySelector('dialog[aria-labelledby="directory-dialog-title"][open]')`)
    const closedDialog = () => waitFor(`!document.querySelector('dialog[aria-labelledby="directory-dialog-title"][open]')`)
    await navigate()
    await waitFor(`document.querySelectorAll('[data-directory-user]').length === 5`)
    assert.equal(await evaluate(`document.querySelector('#directory-user-details h2').textContent`), 'Maya Haddad')
    await browser.capture('users-departments-desktop')
    await input('Search directory users', 'MAYA.HADDAD')
    await waitFor(`document.querySelectorAll('[data-directory-user]').length === 1`)
    await input('Search directory users', '')
    await select('Directory role filter', 'Viewer')
    await waitFor(`document.querySelectorAll('[data-directory-user]').length === 3`)
    await evaluate(`document.querySelector('[aria-controls="directory-more-filters"]').click()`)
    await waitFor(`!!document.getElementById('directory-more-filters')`)
    await select('Directory department filter', 'engineering')
    await select('Directory status filter', 'Active')
    await button('Apply filters')
    await waitFor(`document.querySelectorAll('[data-directory-user]').length === 2`)
    await select('Directory role filter', '')
    await evaluate(`document.querySelector('[aria-controls="directory-more-filters"]').click()`)
    await button('Reset')
    await waitFor(`document.querySelectorAll('[data-directory-user]').length === 5`)
    await click('Select user Omar Saleh')
    await waitFor(`document.querySelector('#directory-user-details h2').textContent === 'Omar Saleh'`)
    await evaluate(`document.getElementById('directory-row-omar').focus()`)
    await browser.key('ArrowDown', 40)
    await waitFor(`document.querySelector('#directory-user-details h2').textContent === 'Lina Nasser'`)
    await click('Deselect directory user')
    await waitFor(`document.querySelector('#directory-user-details').textContent.includes('No user selected')`)
    await click('Select user Maya Haddad')
    await waitFor(`document.querySelector('#directory-user-details h2')?.textContent === 'Maya Haddad'`)
    await button('Edit user permissions ↗')
    await openDialog()
    await select('User department', 'product')
    await select('User role', 'Administrator')
    await button('Save changes')
    await closedDialog()
    assert.equal(await evaluate(`document.querySelector('#directory-user-details').textContent.includes('Product')`), true)
    assert.equal(await evaluate(`document.querySelector('#directory-user-details').textContent.includes('Administrator')`), true)
    await tab(1)
    await click('Inspect department Product')
    await waitFor(`document.querySelector('#directory-content').textContent.includes('1 current demo members')`)
    await button('Maya Haddad')
    await waitFor(`document.getElementById('directory-tab-0').getAttribute('aria-selected') === 'true'`)
    await menu('Disable account')
    await openDialog()
    await button('Cancel')
    await closedDialog()
    assert.equal(await evaluate(`document.querySelector('#directory-user-details').textContent.includes('Inactive')`), false)
    await menu('Disable account')
    await openDialog()
    await button('Confirm disable')
    await closedDialog()
    await waitFor(`document.querySelector('#directory-user-details').textContent.includes('Inactive')`)
    assert.equal(await evaluate(`Array.from(document.querySelectorAll('#directory-user-details dd')).filter(dd => dd.textContent === 'Not allowed').length`), 4)
    await menu('Re-enable account')
    await openDialog()
    await button('Confirm re-enable')
    await closedDialog()
    await menu('View local activity')
    await openDialog()
    assert.equal(await evaluate(`document.querySelector('dialog[open]').textContent.includes('re-enabled')`), true)
    await browser.key('Escape', 27)
    await closedDialog()
    await button('Add User')
    await openDialog()
    await button('Add demo user')
    await waitFor(`document.querySelector('input[aria-label="User name"]').getAttribute('aria-invalid') === 'true'`)
    await input('User name', 'Demo New User')
    await input('User email', 'MAYA.HADDAD@MENAIQ.COM')
    await button('Add demo user')
    await waitFor(`document.querySelector('dialog[open]').textContent.includes('already belongs')`)
    await input('User email', 'broken-email')
    await button('Add demo user')
    await waitFor(`document.querySelector('dialog[open]').textContent.includes('valid email')`)
    await input('User email', 'new.user@menaiq.example')
    await select('User department', 'marketing')
    await select('User role', 'Viewer')
    await button('Add demo user')
    await closedDialog()
    await waitFor(`document.querySelector('#directory-user-details h2').textContent === 'Demo New User'`)
    assert.equal(await evaluate(`document.querySelectorAll('[data-directory-user]').length`), 1)
    assert.equal(await evaluate(`document.querySelector('[aria-label="Users page 2"]').getAttribute('aria-current')`), 'page')
    await click('Previous users page')
    await waitFor(`document.querySelectorAll('[data-directory-user]').length === 5`)
    await tab(2)
    assert.equal(await evaluate(`!!document.querySelector('[aria-label="Directory role permissions"]')`), true)
    await tab(3)
    assert.equal(await evaluate(`document.querySelector('#directory-content').textContent.includes('Department scope')`), true)
    await evaluate(`document.getElementById('directory-tab-3').focus()`)
    await browser.key('Home', 36)
    await waitFor(`document.getElementById('directory-tab-0').getAttribute('aria-selected') === 'true'`)
    for (const [query,text] of [['?state=loading','Loading directory'],['?state=empty','No users found'],['?state=error','Unable to load directory'],['?user=none','No user selected'],['?user=missing','User not available in this view'],['?role=viewer','Viewer demo'],['?role=manager&scope=data','Department Manager demo']]) {
      await navigate(query)
      await waitFor(`document.querySelector('main').textContent.includes(${JSON.stringify(text)})`)
      if (query.includes('error')) { await button('Try again'); await waitFor(`document.querySelectorAll('[data-directory-user]').length === 5`) }
      if (query.includes('empty')) { await button('Reset filters'); await waitFor(`document.querySelectorAll('[data-directory-user]').length === 5`) }
      if (query.includes('role=')) {
        assert.equal(await evaluate(`Array.from(document.querySelectorAll('main button')).find(button => button.textContent.includes('Add User')).disabled`), true)
        assert.equal(await evaluate(`Array.from(document.querySelectorAll('main button')).find(button => button.textContent.includes('Edit user permissions')).disabled`), true)
      }
      if (query.includes('manager')) assert.deepEqual(await evaluate(`Array.from(document.querySelectorAll('[data-directory-user]')).map(row => row.getAttribute('data-directory-user'))`), ['adam'])
    }
    await navigate('?role=manager&scope=data&user=maya')
    await waitFor(`document.querySelector('#directory-user-details').textContent.includes('User not available')`)
    await navigate('?role=manager&scope=data&department=engineering')
    await waitFor(`document.querySelector('main').textContent.includes('No users found')`)
    await browser.viewport(390, 844)
    await navigate()
    assert.equal(await evaluate(`document.documentElement.scrollWidth <= innerWidth`), true)
    await browser.capture('users-departments-mobile')
    await button('Add User')
    await openDialog()
    assert.equal(await evaluate(`document.documentElement.scrollWidth <= innerWidth`), true)
    await browser.key('Escape', 27)
    await closedDialog()
    await browser.viewport(1588, 991)
    for (const [route,title,name] of previous) {
      await browser.navigate(route,title); await ready(name); await browser.capture(name + '-after-users')
      assert.equal((await readFile('.browser-qa/' + name + '-before-users.png')).equals(await readFile('.browser-qa/' + name + '-after-users.png')), true, title + ' must remain visually byte-identical')
    }
    assert.deepEqual(browser.errors, [])
    console.log('Users & Departments browser checks passed: search, combined filters, selection, tabs, edit, role/department changes, confirmation/cancel/re-enable, activity, add validation, pagination, all states, scoped Manager and Viewer permissions, keyboard and mobile. All eight prior page screenshots are byte-identical.')
  }
} finally { await browser.close() }
